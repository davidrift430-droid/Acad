import { test, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
const SRC = path.resolve(__dirname, '../src');
import { DICT } from '../src/i18n/dict';
import { STUDIES } from '../src/data/science';
import { MUSCLES, EQUIPMENT, EXERCISES } from '../src/data';
import { VOLUME_GROUPS } from '../src/core/training';
test('all i18n keys exist', () => {
  const files = fs.readdirSync(SRC, { recursive: true }) as string[];
  const src = files.filter((f) => /\.tsx?$/.test(f)).map((f) => fs.readFileSync(path.join(SRC, f), 'utf8')).join('\n');
  const keys = new Set([...src.matchAll(/\bt\('([a-zA-Z0-9_.]+)'/g)].map((m) => m[1]!));
  ['tab.train','tab.library','tab.lab','tab.diet','tab.more','nav.history','more.profile','gen.progression','gen.joints'].forEach((k) => keys.add(k));
  MUSCLES.forEach((m) => keys.add('muscle.' + m));
  new Set(EXERCISES.map((e) => e.eq)).forEach((e) => keys.add('eq.' + e));
  EQUIPMENT.forEach((e) => keys.add('eq.' + e));
  VOLUME_GROUPS.forEach((g) => keys.add('group.' + g));
  ['L','M','S'].forEach((x) => keys.add('peak.' + x)); [1,2,3].forEach((x) => { keys.add('cns.' + x); keys.add('level.' + x); keys.add('onb.level' + x); });
  ['D','A','B','F'].forEach((x) => keys.add('profile.' + x));
  ['insufficient','losing','slow','on_target','fast'].forEach((x) => keys.add('bulk.' + x));
  ['progressing','not_gaining','stagnant','insufficient'].forEach((x) => keys.add('alarm.' + x));
  ['volume','body','strength','history'].forEach((x) => keys.add('lab.tab.' + x));
  ['bulk','maintain','cut'].forEach((x) => { keys.add('goal.' + x); keys.add('diet.goalNote.' + x); });
  ['dark','light','system'].forEach((x) => keys.add('theme.' + x));
  ['front','side','back'].forEach((x) => keys.add('pose.' + x));
  ['m','f'].forEach((x) => keys.add('sex.' + x)); ['gym','home'].forEach((x) => keys.add('equip.' + x));
  ['knee','lowerBack','shoulder','elbow'].forEach((x) => keys.add('joint.' + x));
  [1.375,1.55,1.725,1.9].forEach((x) => keys.add('act.' + x));
  new Set(STUDIES.map((s) => s.topic)).forEach((x) => keys.add('sci.topic.' + x));
  ['full','ul','ulppl','ppl'].forEach((x) => { keys.add('split.' + x); keys.add('gen.split.' + x); });
  ['full','upper','lower','push','pull','legs'].forEach((x) => keys.add('day.' + x));
  [2,3,4,5,6].forEach((x) => keys.add('onb.split' + x));
  ['breakfast','lunch','preworkout','dinner','snack','supper'].forEach((x) => keys.add('meal.' + x));
  ['sets','repMin','repMax','restSec'].forEach((x) => keys.add('prog.' + x));
  const missing = [...keys].filter((k) => !DICT[k]);
  const empty = Object.entries(DICT).filter(([, v]) => v.some((s) => !s)).map(([k]) => k);
  expect(missing).toEqual([]);
  expect(empty).toEqual([]);
});
